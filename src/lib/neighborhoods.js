function createSlug(name) {
  return name
    .trim()
    .replace(/[ًٌٍَُِّْـ]/g, '')
    .replace(/[أإآ]/g, 'ا')
    .replace(/ة/g, 'ه')
    .replace(/ى/g, 'ي')
    .replace(/ؤ/g, 'و')
    .replace(/ئ/g, 'ي')
    .replace(
      /[^\u0621-\u063A\u0641-\u064A0-9]+/g,
      '-',
    )
    .replace(/^-+|-+$/g, '')
}

function renderTemplate(template, name) {
  return template.replaceAll('{name}', name)
}

