function createSlug(name) {
  return name
    .trim()
    .replace(/[ًٌٍَُِّْـ]/g, '')
    .replace(/[أإآ]/g, 'ا')
    .replace(/ة/g, 'ه')
    .replace(/ى/g, 'ي')
    .replace(/ؤ/g, 'و')
    .replace(/ئ/g, 'ي')
    .replace(/[^\u0621-\u063A\u0641-\u064A0-9]+/g, '-')
    .replace(/^-+|-+$/g, '')
}

const rawProfiles = RAW_NEIGHBORHOODS.map(
  (name, index) => {
    const profile =
      AREA_PROFILES[index % AREA_PROFILES.length]

    const opener =
      OPENERS[index % OPENERS.length]
        .replace('{name}', name)

    const secondParagraph =
      SECOND_PARAGRAPHS[
        index % SECOND_PARAGRAPHS.length
      ]

    return {
      name,

      slug:
        createSlug(name),

      primaryKeyword:
        `كهربائي ${name} جدة`,

      title:
        `كهربائي في حي ${name} بجدة | نور جدة للكهرباء`,

      description:
        `كهربائي منازل في حي ${name} بجدة لخدمات ${profile.keywords}، مع تواصل مباشر لتحديد احتياج المنزل ونطاق العمل المطلوب.`,

      intro:
        `${opener} ${profile.angle}`,

      secondParagraph,

      focus:
        profile.keywords,
    }
  },
)

export const NEIGHBORHOODS =
  rawProfiles

export const NEIGHBORHOOD_PATHS =
  NEIGHBORHOODS.map(
    (neighborhood) =>
      `/neighborhoods/${neighborhood.slug}`,
  )

export function getNeighborhoodBySlug(
  slug,
) {
  return NEIGHBORHOODS.find(
    (neighborhood) =>
      neighborhood.slug === slug,
  )
}

export function getRelatedNeighborhoods(
  currentSlug,
  count = 6,
) {
  const currentIndex =
    NEIGHBORHOODS.findIndex(
      (neighborhood) =>
        neighborhood.slug === currentSlug,
    )

  if (currentIndex < 0) {
    return []
  }

  return Array.from(
    { length: count },
    (_, offset) =>
      NEIGHBORHOODS[
        (currentIndex + offset + 1) %
          NEIGHBORHOODS.length
      ],
  )
}