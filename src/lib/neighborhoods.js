export function getNeighborhoodBySlug(
  slug,
) {
  const normalizedSlug =
    String(slug ?? '')
      .trim()
      .replace(
        /^\/+|\/+$/g,
        '',
      )

  return (
    NEIGHBORHOODS_BY_SLUG.get(
      normalizedSlug,
    ) ?? null
  )
}

export function getRelatedNeighborhoods(
  slug,
  limit = 6,
) {
  const current =
    getNeighborhoodBySlug(
      slug,
    )

  if (!current) {
    return []
  }

  const safeLimit = Math.min(
    Math.max(
      Number(limit) || 0,
      0,
    ),
    NEIGHBORHOODS.length - 1,
  )

  if (safeLimit === 0) {
    return []
  }

  const currentIndex =
    NEIGHBORHOODS.findIndex(
      (neighborhood) =>
        neighborhood.slug ===
        current.slug,
    )

  if (currentIndex === -1) {
    return []
  }

  const related = []

  for (
    let offset = 1;
    offset <=
      NEIGHBORHOODS.length &&
    related.length <
      safeLimit;
    offset += 1
  ) {
    const candidate =
      NEIGHBORHOODS[
        (currentIndex +
          offset) %
          NEIGHBORHOODS.length
      ]

    if (
      candidate.slug !==
      current.slug
    ) {
      related.push(candidate)
    }
  }

  return related
}

export function getNeighborhoodFaqs(
  neighborhood,
  limit = 4,
) {
  if (!neighborhood) {
    return []
  }

  const safeLimit = Math.min(
    Math.max(
      Number(limit) || 0,
      0,
    ),
    FAQ_TEMPLATES.length,
  )

  if (safeLimit === 0) {
    return []
  }

  const start =
    Number(
      neighborhood.faqStart,
    ) || 0

  const faqs = []

  for (
    let offset = 0;
    offset <
      FAQ_TEMPLATES.length &&
    faqs.length <
      safeLimit;
    offset += 1
  ) {
    const template =
      FAQ_TEMPLATES[
        (start + offset) %
          FAQ_TEMPLATES.length
      ]

    faqs.push({
      question:
        replaceNeighborhoodName(
          template.question,
          neighborhood.name,
        ),

      answer:
        replaceNeighborhoodName(
          template.answer,
          neighborhood.name,
        ),
    })
  }

  return faqs
}

