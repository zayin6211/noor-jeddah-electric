export function getNeighborhoodBySlug(
  slug,
) {
  return NEIGHBORHOODS.find(
    (neighborhood) =>
      neighborhood.slug === slug,
  )
}

export function getRelatedNeighborhoods(
  currentSlug,
  count = 6,
) {
  const currentIndex =
    NEIGHBORHOODS.findIndex(
      (neighborhood) =>
        neighborhood.slug === currentSlug,
    )

  if (currentIndex < 0) {
    return []
  }

  const safeCount =
    Math.max(
      0,
      Math.min(
        count,
        NEIGHBORHOODS.length - 1,
      ),
    )

  return Array.from(
    { length: safeCount },
    (_, offset) =>
      NEIGHBORHOODS[
        (
          currentIndex +
          offset +
          1
        ) %
          NEIGHBORHOODS.length
      ],
  )
}

export function getNeighborhoodFaqs(
  neighborhood,
  count = 4,
) {
  if (!neighborhood) {
    return []
  }

  const safeCount =
    Math.max(
      0,
      Math.min(
        count,
        FAQ_TOPICS.length,
      ),
    )

  return Array.from(
    { length: safeCount },
    (_, offset) => {
      const topic =
        FAQ_TOPICS[
          (
            neighborhood.faqStartIndex +
            offset
          ) %
            FAQ_TOPICS.length
        ]

      return {
        question:
          renderTemplate(
            topic.question,
            neighborhood.name,
          ),

        answer:
          renderTemplate(
            topic.answer,
            neighborhood.name,
          ),
      }
    },
  )
}