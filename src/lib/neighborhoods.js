function replaceNeighborhoodName(
  text,
  name,
) {
  return text.replaceAll(
    '{name}',
    name,
  )
}

function createSlug(name) {
  return name
    .trim()
    .toLowerCase()
    .replace(/[ًٌٍَُِّْـ]/g, '')
    .replace(/\s+/g, '-')
    .replace(
      /[^\u0600-\u06ff0-9a-z-]/gi,
      '',
    )
    .replace(/-+/g, '-')
    .replace(/^-|-$/g, '')
}

