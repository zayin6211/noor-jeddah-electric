function createSlug(name) {
  return name
    .trim()
    .replace(/[ًٌٍَُِّْـ]/g, '')
    .replace(/[أإآ]/g, 'ا')
    .replace(/ة/g, 'ه')
    .replace(/ى/g, 'ي')
    .replace(/ؤ/g, 'و')
    .replace(/ئ/g, 'ي')
    .replace(/[^\u0621-\u063A\u0641-\u064A0-9]+/g, '-')
    .replace(/^-+|-+$/g, '')
}

function getProfileIndex(index) {
  return index % AREA_PROFILES.length
}

function getScenarioIndex(index) {
  return (index * 7 + 3) % SERVICE_SCENARIOS.length
}

function getFaqStartIndex(index) {
  return (index * 11 + 5) % FAQ_TOPICS.length
}

const rawProfiles = RAW_NEIGHBORHOODS.map(
  (name, index) => {
    const profileIndex =
      getProfileIndex(index)

    const profile =
      AREA_PROFILES[profileIndex]

    const opener =
      OPENERS[
        index % OPENERS.length
      ].replace('{name}', name)

    const secondParagraph =
      SECOND_PARAGRAPHS[
        (index * 3) %
          SECOND_PARAGRAPHS.length
      ]

    const scenarioIndex =
      getScenarioIndex(index)

    const faqStartIndex =
      getFaqStartIndex(index)

    return {
      name,

      slug:
        createSlug(name),

      primaryKeyword:
        `كهربائي ${name} جدة`,

      title:
        `كهربائي في حي ${name} بجدة | نور جدة للكهرباء`,

      description:
        `كهربائي منازل في حي ${name} بجدة لخدمات ${profile.keywords}، مع تواصل مباشر لتحديد احتياج المنزل ونطاق العمل المطلوب.`,

      intro:
        `${opener} ${profile.angle}`,

      secondParagraph,

      focus:
        profile.keywords,

      profileIndex,

      scenarioIndex,

      needText:
        profile.need,

      tipText:
        profile.tip,

      scenarioText:
        SERVICE_SCENARIOS[
          scenarioIndex
        ].paragraph(name),

      scenarioHeading:
        SERVICE_SCENARIOS[
          scenarioIndex
        ].heading,

      faqStartIndex,
    }
  },
)

