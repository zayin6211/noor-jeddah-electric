export function getNeighborhoodBySlug(
  slug,
) {
  return NEIGHBORHOODS.find(
    (neighborhood) =>
      neighborhood.slug === slug,
  )
}

export function getRelatedNeighborhoods(
  currentSlug,
  count = 6,
) {
  const currentIndex =
    NEIGHBORHOODS.findIndex(
      (neighborhood) =>
        neighborhood.slug === currentSlug,
    )

  if (currentIndex < 0) {
    return []
  }

  return Array.from(
    { length: count },
    (_, offset) =>
      NEIGHBORHOODS[
        (currentIndex + offset + 1) %
          NEIGHBORHOODS.length
      ],
  )
}

export function getNeighborhoodFaqs(
  neighborhood,
  count = 4,
) {
  if (!neighborhood) {
    return []
  }

  return Array.from(
    { length: count },
    (_, offset) => {
      const topic =
        FAQ_TOPICS[
          (neighborhood.faqStartIndex +
            offset) %
            FAQ_TOPICS.length
        ]

      return {
        question:
          topic.question(
            neighborhood.name,
          ),
        answer:
          topic.answer(
            neighborhood.name,
          ),
      }
    },
  )
}